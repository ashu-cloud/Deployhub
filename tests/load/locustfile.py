class ProjectApiUser(HttpUser):
    """Authenticated project list/create/get mix."""

    wait_time = between(0.2, 1.0)
    weight = 4
    host = PROJECT_URL

    def on_start(self):
        self.headers = {"Authorization": f"Bearer {_jwt()}"}
        self.project_ids = []

    @tag("api")
    @task(10)
    def list_projects(self):
        self.client.get("/projects/", headers=self.headers, name="projects:list")

    @tag("api")
    @task(2)
    def create_project(self):
        suffix = uuid.uuid4().hex[:10]
        with self.client.post(
            "/projects/",
            headers=self.headers,
            json={"repo_name": f"load-{suffix}", "repo_url": f"https://github.com/load/{suffix}"},
            name="projects:create",
            catch_response=True,
        ) as response:
            if response.status_code == 201:
                self.project_ids.append(response.json()["id"])
                response.success()
            elif response.status_code in {400, 401, 409}:
                response.success()
            else:
                response.failure(f"unexpected {response.status_code}")

    @tag("api")
    @task(4)
    def get_project(self):
        if not self.project_ids:
            self.list_projects()
            return
        pid = self.project_ids[-1]
        self.client.get(f"/projects/{pid}", headers=self.headers, name="projects:get")


class WebhookStormUser(HttpUser):
    """High-rate signed webhook deliveries (unique delivery ids)."""

    wait_time = between(0.05, 0.2)
    weight = 5
    host = PROJECT_URL

    def on_start(self):
        self.project_id = str(uuid.uuid4())

    @tag("webhook")
    @task
    def simulate_webhook_push(self):
        payload = {
            "ref": "refs/heads/main",
            "after": uuid.uuid4().hex + uuid.uuid4().hex[:8],
            "repository": {"clone_url": "https://github.com/test/repo"},
        }
        body = json.dumps(payload, separators=(",", ":")).encode("utf-8")
        headers = {
            "Content-Type": "application/json",
            "X-Hub-Signature-256": _sign(body),
            "X-GitHub-Delivery": str(uuid.uuid4()),
            "X-GitHub-Event": "push",
        }
        with self.client.post(
            f"/webhooks/github/{self.project_id}",
            data=body,
            headers=headers,
            name="webhooks:push",
            catch_response=True,
        ) as response:
            if response.status_code in {200, 400, 404}:
                response.success()
            else:
                response.failure(f"unexpected {response.status_code}")


