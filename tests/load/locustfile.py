class UnauthenticatedFloodUser(HttpUser):
    """Confirm protected routes stay rejected under load."""

    wait_time = constant(0.1)
    weight = 2
    host = PROJECT_URL

    @tag("security")
    @task
    def list_without_token(self):
        with self.client.get("/projects/", name="projects:unauth", catch_response=True) as response:
            if response.status_code in {401, 403}:
                response.success()
            else:
                response.failure(f"expected 401/403, got {response.status_code}")


class ConcurrentRaceUser(HttpUser):
    """Zero-wait bursts that hammer the same resources (locks, duplicates, lists)."""

    wait_time = constant(0)
    weight = 3
    host = PROJECT_URL

    def on_start(self):
        self.headers = {"Authorization": f"Bearer {_jwt()}"}
        self.delivery_id = str(uuid.uuid4())
        self.project_id = str(uuid.uuid4())
        self.repo_name = f"locust-{uuid.uuid4().hex[:8]}"

    @tag("concurrency")
    @task(4)
    def duplicate_create(self):
        with self.client.post(
            "/projects/",
            headers=self.headers,
            json={
                "repo_name": self.repo_name,
                "repo_url": f"https://github.com/locust/{self.repo_name}",
            },
            name="concurrency:duplicate-create",
            catch_response=True,
        ) as response:
            if response.status_code in {201, 400, 401, 409, 422}:
                response.success()
            else:
                response.failure(f"unexpected {response.status_code}")

    @tag("concurrency")
    @task(6)
    def same_delivery_webhook(self):
        payload = {
            "ref": "refs/heads/main",
            "after": "a" * 40,
            "repository": {"clone_url": "https://github.com/test/repo"},
        }
        body = json.dumps(payload, separators=(",", ":")).encode("utf-8")
        headers = {
            "Content-Type": "application/json",
            "X-Hub-Signature-256": _sign(body),
            "X-GitHub-Delivery": self.delivery_id,
            "X-GitHub-Event": "push",
        }
        with self.client.post(
            f"/webhooks/github/{self.project_id}",
            data=body,
            headers=headers,
            name="concurrency:same-delivery",
            catch_response=True,
        ) as response:
            if response.status_code in {200, 400, 404}:
                response.success()
            else:
                response.failure(f"unexpected {response.status_code}")

    @tag("concurrency")
    @task(5)
    def parallel_list(self):
        self.client.get("/projects/", headers=self.headers, name="concurrency:list")


